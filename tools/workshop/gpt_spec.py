def size_text(w, h):
    f = lambda v: ('%g' % round(v / CELL, 2))
    return f'{f(w)} x {f(h)} ช่อง'

def build():
    out = ['# สเปกให้ GPT ทำแม่แบบทั้งแผ่น (ไม่แนบภาพแม่แบบ)', '',
           'สร้างอัตโนมัติจาก `tools/workshop/items.py` ด้วย `python3 tools/workshop/gpt_spec.py` อย่าแก้มือ แต่ละแผ่นคัดลอกข้อความ "กติกา" + "รายการ" ไปวางในแชต GPT ทีละแผ่น ผมรับภาพกลับมาแล้วตัดและตรวจสเกล', '']
    for n, sh in enumerate(SHEETS, 1):
        its = [i for i in ITEMS if i[5] in sh['categories']]
        out += [f"## {sh['title']} ({len(its)} ชิ้น)", '', '### กติกา (ส่งก่อน)', '', COMMON,
                '### รายการ (ส่งต่อท้ายกติกา)', f"วาดทั้งหมด {len(its)} ชิ้น ตามลำดับนี้:", '']
        for k, i in enumerate(its, 1):
            out.append(f"{k}. **{i[6]}** — กรอบ {size_text(i[3], i[4])} — {DESC.get(i[0], '')}")
        out.append('')
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    open('docs/GPT_SPEC.md', 'w', encoding='utf-8').write(build())
    missing = [i[0] for i in ITEMS if i[0] not in DESC]
    print('written docs/GPT_SPEC.md; items without text:', missing)
